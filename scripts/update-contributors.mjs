#!/usr/bin/env node
/**
 * Refresh the contributor faces in the "Meet us" section of README.md.
 *
 * Usage:
 *   node scripts/update-contributors.mjs             # fetch from the API, then render
 *   node scripts/update-contributors.mjs --offline   # regenerate from the existing JSON, no API
 *   node scripts/update-contributors.mjs --check     # verify README.md matches the JSON
 *
 * Set GITHUB_TOKEN to raise the API rate limit: GITHUB_TOKEN=$(gh auth token) node …
 */

import { readFileSync, writeFileSync } from 'fs';
import { fileURLToPath } from 'url';
import { dirname, join } from 'path';

const ORG = 'roostorg';
const AVATAR_SIZE = 96;
const DISPLAY_SIZE = 48;
const START = '<!-- contributors:start -->';
const END = '<!-- contributors:end -->';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dataPath = join(root, 'data', 'contributors.json');
const excludePath = join(root, 'data', 'contributors-exclude.json');
const readmePath = join(root, 'README.md');

const offline = process.argv.includes('--offline');
const check = process.argv.includes('--check');

async function api(path) {
  const headers = { Accept: 'application/vnd.github+json', 'User-Agent': `${ORG}-community` };
  if (process.env.GITHUB_TOKEN) headers.Authorization = `Bearer ${process.env.GITHUB_TOKEN}`;

  const results = [];
  let url = `https://api.github.com${path}`;
  while (url) {
    const response = await fetch(url, { headers });
    if (!response.ok) {
      throw new Error(`GET ${url} failed: ${response.status} ${response.statusText}`);
    }
    results.push(...(await response.json()));
    // The Link header is the only reliable way to page the contributors endpoint.
    url = (response.headers.get('link') ?? '').match(/<([^>]+)>;\s*rel="next"/)?.[1] ?? null;
  }
  return results;
}

function keep(user, exclude) {
  return user.type === 'User'
    && !user.login.endsWith('[bot]')
    && !exclude.has(user.login.toLowerCase());
}

async function fetchContributors(exclude) {
  const repos = (await api(`/orgs/${ORG}/repos?type=public&per_page=100`)).filter((repo) => !repo.fork);
  process.stderr.write(`Found ${repos.length} public repos in ${ORG}\n`);

  const people = new Map();
  for (const repo of repos) {
    for (const user of await api(`/repos/${ORG}/${repo.name}/contributors?per_page=100`)) {
      if (!keep(user, exclude)) continue;
      const existing = people.get(user.id);
      if (existing) {
        existing.contributions += user.contributions;
      } else {
        people.set(user.id, {
          login: user.login,
          id: user.id,
          avatar_url: `https://avatars.githubusercontent.com/u/${user.id}`,
          html_url: user.html_url,
          contributions: user.contributions,
        });
      }
    }
  }

  return [...people.values()].sort(
    (a, b) => b.contributions - a.contributions || a.login.toLowerCase().localeCompare(b.login.toLowerCase())
  );
}

function render(contributors) {
  const faces = contributors.map((person) => {
    const src = `${person.avatar_url}?s=${AVATAR_SIZE}`;
    const img = `<img src="${src}" alt="${person.login}" width="${DISPLAY_SIZE}" height="${DISPLAY_SIZE}" loading="lazy">`;
    return `<a href="${person.html_url}" title="${person.login}">${img}</a>`;
  });

  // No blank lines inside the div: both mdBook and GitHub end the raw HTML block there.
  return [
    START,
    '<!-- Generated by scripts/update-contributors.mjs — do not edit by hand. -->',
    '<div class="contributors">',
    ...faces,
    '</div>',
    END,
  ].join('\n');
}

function replaceBlock(readme, block) {
  const start = readme.indexOf(START);
  const end = readme.indexOf(END);
  if (start === -1 || end === -1) {
    throw new Error(`Could not find the ${START} / ${END} markers in README.md`);
  }
  return readme.slice(0, start) + block + readme.slice(end + END.length);
}

const exclude = new Set(
  JSON.parse(readFileSync(excludePath, 'utf8')).exclude.map((login) => login.toLowerCase())
);

// Re-filter even when reading from disk, so a new entry in the exclude list
// takes effect in README.md right away. Only a fetch rewrites the JSON, so
// removing an entry is always recoverable.
const contributors =
  offline || check
    ? JSON.parse(readFileSync(dataPath, 'utf8')).contributors.filter(
        (person) => !exclude.has(person.login.toLowerCase())
      )
    : await fetchContributors(exclude);

const json = `${JSON.stringify({ contributors }, null, 2)}\n`;
const readme = replaceBlock(readFileSync(readmePath, 'utf8'), render(contributors));

if (check) {
  const stale = [
    readFileSync(dataPath, 'utf8') !== json && 'data/contributors.json',
    readFileSync(readmePath, 'utf8') !== readme && 'README.md',
  ].filter(Boolean);
  if (stale.length) {
    process.stderr.write(`Out of date: ${stale.join(', ')}\n`);
    process.exit(1);
  }
  process.stderr.write('Up to date\n');
} else {
  if (!offline) writeFileSync(dataPath, json);
  writeFileSync(readmePath, readme);
  process.stderr.write(`Wrote ${contributors.length} contributors\n`);
}
